// Upload a new document: stored in Document Engine under a fresh id, which
// becomes the current document for search, injection and the viewer.
app.post(
  "/api/upload-document",
  express.raw({ type: ["application/pdf", "application/octet-stream"], limit: "100mb" }),
  async (req, res) => {
    try {
      if (!req.body?.length) return res.status(400).json({ error: "Empty upload." });
      const name = String(req.query.name || "uploaded.pdf");
      const newId = `doc-${Date.now()}`;
      const form = new FormData();
      form.append("file", new Blob([req.body], { type: "application/pdf" }), name);
      form.append("document_id", newId);
      form.append("title", name);
      const up = await de("/api/documents", { method: "POST", body: form });
      if (!up.ok) {
        return res.status(502).json({ error: `Document Engine rejected the upload: ${await up.text()}` });
      }
      DOCUMENT_ID = newId;
      processedEvents = null;
      console.log(`[upload] now serving document "${newId}" (${name})`);
      res.json({ documentId: newId, name });
    } catch (err) {
      console.error(err);
      res.status(500).json({ error: String(err) });
    }
  }
);

// Standalone (WebAssembly) viewer support: the browser renders the PDF
// locally with the Web SDK's WASM engine, so it keeps working offline once
// loaded. The document and the server-injected annotations are fetched once.

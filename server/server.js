async function wipePocAnnotations() {
  const res = await de(`/api/documents/${DOCUMENT_ID}/annotations`, {
    headers: { Accept: "application/json" },
  });
  if (!res.ok) return;
  const body = await res.json();
  const annotations = body?.data?.annotations ?? body?.annotations ?? [];
  const mine = annotations.filter((ann) => (ann.content ?? ann)?.creatorName === CREATOR);
  await mapPool(mine, (ann) => de(`/api/documents/${DOCUMENT_ID}/annotations/${ann.id}`, { method: "DELETE" }), 8);
}

// Batch injection: every annotation of every event goes to the Annotations
// API in a single call. Returns one {ok, id} per submitted annotation; the id
// lets the frontend select the annotation when its event is clicked.
async function createAnnotationsBatch(contents) {
  if (contents.length === 0) return [];
  const res = await de(`/api/documents/${DOCUMENT_ID}/annotations`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ annotations: contents.map((c) => ({ content: c, user_id: "annotation-poc" })) }),
  });
  const body = await res.json().catch(() => null);
  if (!res.ok || !body) {
    console.error(`[inject] batch creation failed: ${res.status}`);
    return contents.map(() => ({ ok: false, id: null }));
  }
  const created = body.data ?? [];
  if (body.result === "success") {
    return contents.map((_, i) => ({ ok: true, id: created[i]?.id ?? null }));
  }
  const failing = new Set(
    (body.failing_paths ?? []).map((f) => {
      const m = /\[(\d+)\]/.exec(f.path ?? "");
      return m ? Number(m[1]) : -1;
    })
  );
  console.error(`[inject] batch: ${failing.size}/${contents.length} annotation(s) rejected:`, JSON.stringify(body.failing_paths));
  let next = 0;
  return contents.map((_, i) => (failing.has(i) ? { ok: false, id: null } : { ok: true, id: created[next++]?.id ?? null }));
}

function annotationForPart(event, part, method) {
  const now = new Date().toISOString();
  const base = {
    v: 2,
    pageIndex: part.pageIndex,
    opacity: 1,
    createdAt: now,
    updatedAt: now,
    creatorName: CREATOR,
    customData: { eventId: event.id, method },
  };
  if (part.rects) {
    return {
      ...base,
      type: "pspdfkit/markup/highlight",
      rects: part.rects,
      bbox: rectsUnion(part.rects),
      color: event.color,
      blendMode: "multiply",
    };
  }
  // Coordinates fallback: rectangle over the zone the LLM pointed at.
  return {
    ...base,
    type: "pspdfkit/shape/rectangle",
    bbox: part.boundingBox,
    strokeColor: event.color,
    strokeWidth: 2,
  };
}

let processedEvents = null;

async function processLlmOutput(rawEvents) {
  const pageCount = await getPageCount();
  searchCache = new Map();
  pageTextCache = new Map();
  await wipePocAnnotations();
  const palette = ["#FFD54F", "#4FC3F7", "#81C784", "#F48FB1", "#FF8A65", "#B39DDB", "#4DB6AC"];
  const events = rawEvents.map(normalizeEvent);
  events.forEach((event, i) => {
    if (!event.color) event.color = palette[i % palette.length];
  });
  const resolutions = await mapPool(events, (event) => resolveEvent(event, pageCount), 6);
  const results = [];
  const batch = [];
  for (const [i, event] of events.entries()) {
    const resolution = resolutions[i];
    for (const [partIndex, part] of resolution.parts.entries()) {
      batch.push({ content: annotationForPart(event, part, resolution.method), eventIndex: i, partIndex });
    }
    results.push({
      id: event.id,
      title: event.title,
      date: event.date,
      description: event.description,
      color: event.color,
      llm: { text: event.text, page: event.page, occurrence: event.occurrence, context: event.context, coordinates: event.coordinates },
      method: resolution.method,
      notes: resolution.notes,
      parts: resolution.parts.map((p) => ({
        pageIndex: p.pageIndex,
        boundingBox: p.boundingBox ?? rectsUnion(p.rects),
      })),
      annotationsInjected: 0,
    });
  }
  const created = await createAnnotationsBatch(batch.map((b) => b.content));
  created.forEach((r, idx) => {
    if (!r.ok) return;
    const { eventIndex, partIndex } = batch[idx];
    results[eventIndex].annotationsInjected += 1;
    results[eventIndex].parts[partIndex].annotationId = r.id;
  });
  for (const r of results) {
    console.log(`[inject] ${r.id}: ${r.method} (${r.annotationsInjected} annotation(s))`);
  }
  processedEvents = results;
  return results;
}


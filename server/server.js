// Accepts both the PoC's own schema and the pipeline's wire format:
// - "trigger" or "event_trigger_string" is the pipeline's event text field
//   (ours is "text")
// - "page_nr" is 0-based (our "page" is 1-based)
// - "nAppereance" counts the pipeline's emitted events per trigger string, NOT the
//   position of the occurrence in the document, so it is deliberately ignored
// - "occurrence" (per page, reading order, 1-based) or "context"
//   ({before, after} surrounding text) are the supported disambiguators
function normalizeEvent(raw, index) {
  const text = String(raw.text ?? raw.trigger ?? raw.event_trigger_string ?? "").replace(/\s+/g, " ").trim();
  const page = raw.page ?? (raw.page_nr != null ? raw.page_nr + 1 : null);
  const shortText = text.length > 60 ? `${text.slice(0, 57)}...` : text;
  const title = raw.title ?? raw.name ?? raw.event ?? raw.event_title ?? (shortText || `Event ${index + 1}`);
  return {
    id: String(raw.id ?? `evt-${index + 1}`),
    title,
    date: (raw.date || null) ?? null,
    description: raw.description ?? raw.event_description ?? null,
    page,
    occurrence: raw.occurrence ?? null,
    // Character offset of the trigger within the page text (the pipeline
    // holds these); lets the server derive a real per-page occurrence number.
    startIndex: raw.startIndex ?? null,
    context: raw.context ?? null,
    coordinates: raw.coordinates ?? null,
    color: raw.color,
    text,
  };
}

// Locates an event through its surrounding text: the trigger extended with a
// few words of context is far more unique than the trigger alone. The zone it
// resolves to is then used to pick the right occurrence.
async function locateContextZone(event, state) {
  const clean = (s) => String(s ?? "").replace(/\s+/g, " ").trim();
  const words = (s) => clean(s).split(" ").filter(Boolean);
  const before = words(event.context?.before).slice(-6).join(" ");
  const after = words(event.context?.after).slice(0, 6).join(" ");
  const queries = [];
  if (before && after) queries.push(`${before} ${event.text} ${after}`);
  if (before) queries.push(`${before} ${event.text}`);
  if (after) queries.push(`${event.text} ${after}`);
  for (const q of queries) {
    const hits = await searchDocument(q, state.pageCount);
    const onPage = event.page != null ? hits.filter((h) => h.pageIndex === event.page - 1) : hits;
    if (onPage.length === 1) {
      return { pageIndex: onPage[0].pageIndex, bbox: rectsUnion(onPage[0].rects) };
    }
  }
  state.notes.push("context anchor could not be located uniquely; ignored");
  return null;
}

function rectsUnion(rects) {
  const left = Math.min(...rects.map((r) => r[0]));
  const top = Math.min(...rects.map((r) => r[1]));
  const right = Math.max(...rects.map((r) => r[0] + r[2]));
  const bottom = Math.max(...rects.map((r) => r[1] + r[3]));
  return [left, top, right - left, bottom - top];
}

function rectCenter(rect) {
  return { x: rect[0] + rect[2] / 2, y: rect[1] + rect[3] / 2 };
}

// Rects coming from separate fragment searches abut on the same line but do
// not cover the whitespace between them, which shows up as visual seams in
// the highlight. Merge same-line rects when the horizontal gap is small.
function mergeLineRects(rects) {
  const sorted = [...rects].sort((a, b) => a[1] - b[1] || a[0] - b[0]);
  const lines = [];
  for (const r of sorted) {
    const line = lines.find((l) => Math.abs(l.top - r[1]) < Math.max(l.height, r[3]) * 0.6);
    if (line) {
      line.rects.push(r);
      line.top = Math.min(line.top, r[1]);
      line.height = Math.max(line.height, r[3]);
    } else {
      lines.push({ top: r[1], height: r[3], rects: [r] });
    }
  }
  const merged = [];
  for (const line of lines) {
    line.rects.sort((a, b) => a[0] - b[0]);
    let current = [...line.rects[0]];
    for (let i = 1; i < line.rects.length; i++) {
      const r = line.rects[i];
      const gap = r[0] - (current[0] + current[2]);
      if (gap <= 12) {
        const right = Math.max(current[0] + current[2], r[0] + r[2]);
        const top = Math.min(current[1], r[1]);
        const bottom = Math.max(current[1] + current[3], r[1] + r[3]);
        current = [current[0], top, right - current[0], bottom - top];
      } else {
        merged.push(current);
        current = [...r];
      }
    }
    merged.push(current);
  }
  return merged;
}

// Picks the best hit among several, mirroring the pipeline's metadata: the
// pipeline knows the page and the occurrence number of the phrase on that
// page ("handover date, occurrence 2, page 3"). Coordinates are only used
// as an extra disambiguator when the JSON happens to carry them.
function pickBestHit(hits, event, state) {
  // Reading order: page, then top-to-bottom, then left-to-right.
  const sorted = [...hits].sort((a, b) => {
    if (a.pageIndex !== b.pageIndex) return a.pageIndex - b.pageIndex;
    const ua = rectsUnion(a.rects);
    const ub = rectsUnion(b.rects);
    return ua[1] - ub[1] || ua[0] - ub[0];
  });
  if (sorted.length === 1) return sorted[0];

  let candidates = sorted;
  if (event.page != null) {
    const expectedPage = event.page - 1;
    candidates = sorted.filter((h) => h.pageIndex === expectedPage);
    if (candidates.length === 0) {
      const closest = [...sorted].sort(
        (a, b) => Math.abs(a.pageIndex - expectedPage) - Math.abs(b.pageIndex - expectedPage)
      );
      state.notes.push(`no hit on reported page ${event.page}; using closest page ${closest[0].pageIndex + 1}`);
      state.disambiguator = "page";
      return closest[0];
    }
    if (candidates.length === 1) {
      state.notes.push(`${sorted.length} occurrences in document; reported page ${event.page} is unambiguous`);
      state.disambiguator = "page";
      return candidates[0];
    }
  }
  const where = event.page != null ? `on page ${event.page}` : "in document";
  if (event.occurrence != null) {
    const idx = Math.min(Math.max(event.occurrence, 1), candidates.length) - 1;
    state.disambiguator = "occurrence";
    state.notes.push(`${candidates.length} occurrences ${where}; picked occurrence #${idx + 1} in reading order`);
    if (event.occurrence > candidates.length) {
      state.notes.push(`reported occurrence #${event.occurrence} does not exist; clamped to the last one`);
    }
    return candidates[idx];
  }
  if (event._zone) {
    const z = event._zone.bbox;
    const inZone = candidates.filter((c) => {
      if (c.pageIndex !== event._zone.pageIndex) return false;
      const u = rectsUnion(c.rects);
      return u[0] < z[0] + z[2] && z[0] < u[0] + u[2] && u[1] < z[1] + z[3] && z[1] < u[1] + u[3];
    });
    if (inZone.length > 0) {
      state.disambiguator = "context";
      state.notes.push(`${candidates.length} occurrences ${where}; picked the one inside the context-anchor zone`);
      return inZone[0];
    }
  }
  if (event.coordinates) {
    const target = rectCenter([
      event.coordinates.left,
      event.coordinates.top,
      event.coordinates.width,
      event.coordinates.height,
    ]);
    const byDistance = [...candidates].sort((a, b) => {
      const ca = rectCenter(rectsUnion(a.rects));
      const cb = rectCenter(rectsUnion(b.rects));
      const da = (ca.x - target.x) ** 2 + (ca.y - target.y) ** 2;
      const db = (cb.x - target.x) ** 2 + (cb.y - target.y) ** 2;
      return da - db;
    });
    state.disambiguator = "coordinate";
    state.notes.push(`${candidates.length} occurrences ${where}; picked the one closest to the LLM coordinates`);
    return byDistance[0];
  }
  state.disambiguator = "page";
  state.notes.push(`${candidates.length} occurrences ${where}; no occurrence number given, picked the first`);
  return candidates[0];
}

// Recursively resolves a text fragment to page rects. When the exact text is
// not found (LLM paraphrase, or the sentence crosses a page boundary), the
// fragment is split in half at a word boundary and each half is resolved
// independently, down to a minimum fragment size. Returns segments in text
// order; unmatched segments are kept so a later pass can fill the gaps.
async function resolveFragment(text, event, state, depth = 0) {
  const hits = await searchDocument(text, state.pageCount);
  if (hits.length > 0) {
    if (hits.length > 1) state.ambiguous = true;
    const best = pickBestHit(hits, event, state);
    return [{ matched: true, pageIndex: best.pageIndex, rects: best.rects, fragment: text }];
  }
  const words = text.split(/\s+/);
  if (depth >= 3 || words.length < 8) {
    return [{ matched: false, fragment: text }];
  }
  state.split = true;
  const mid = Math.ceil(words.length / 2);
  const left = await resolveFragment(words.slice(0, mid).join(" "), event, state, depth + 1);
  const right = await resolveFragment(words.slice(mid).join(" "), event, state, depth + 1);
  return [...left, ...right];
}

// --- Anchored gap filling -------------------------------------------------
// A fragment that straddles the page break can never be found by a per-page
// text search, no matter how it is halved. But when the text right before it
// and right after it are both located, the missing words can only live in
// the zone between those two anchors. Sub-fragments are searched longest
// first and only hits inside that zone are accepted, which makes even very
// short searches unambiguous.

const readingOrder = (a, b) => {
  if (a.pageIndex !== b.pageIndex) return a.pageIndex - b.pageIndex;
  const ua = rectsUnion(a.rects);
  const ub = rectsUnion(b.rects);
  return ua[1] - ub[1] || ua[0] - ub[0];
};

// True if hit starts after the anchor's last line (or later on the same line).
function isAfter(hit, anchor) {
  if (hit.pageIndex !== anchor.pageIndex) return hit.pageIndex > anchor.pageIndex;
  const first = hit.rects[0];
  const last = anchor.rects[anchor.rects.length - 1];
  const sameLine = Math.abs(first[1] - last[1]) < last[3] * 0.5;
  if (sameLine) return first[0] >= last[0] + last[2] - 2;
  return first[1] > last[1];
}

// True if hit ends before the anchor's first line (or earlier on the same line).
function isBefore(hit, anchor) {
  if (hit.pageIndex !== anchor.pageIndex) return hit.pageIndex < anchor.pageIndex;
  const last = hit.rects[hit.rects.length - 1];
  const first = anchor.rects[0];
  const sameLine = Math.abs(last[1] - first[1]) < first[3] * 0.5;
  if (sameLine) return last[0] + last[2] <= first[0] + 2;
  return last[1] < first[1];
}

async function matchGapInZone(text, prevAnchor, nextAnchor, state) {
  const words = text.split(/\s+/);
  const found = [];
  let lastAnchor = prevAnchor;
  let i = 0;
  while (i < words.length) {
    let advanced = false;
    for (let j = words.length; j > i; j--) {
      const sub = words.slice(i, j).join(" ");
      if (sub.length < 3) break;
      const hits = await searchDocument(sub, state.pageCount);
      const inZone = hits
        .filter((h) => isAfter(h, lastAnchor) && isBefore(h, nextAnchor))
        .sort(readingOrder);
      if (inZone.length > 0) {
        const best = { matched: true, pageIndex: inZone[0].pageIndex, rects: inZone[0].rects, fragment: sub };
        found.push(best);
        lastAnchor = best;
        i = j;
        advanced = true;
        break;
      }
    }
    if (!advanced) i += 1; // skip a word that cannot be located (hyphenation etc.)
  }
  return found;
}

async function fillGapSegments(segments, state) {
  for (let i = 0; i < segments.length; i++) {
    if (segments[i].matched) continue;
    const prev = [...segments.slice(0, i)].reverse().find((s) => s.matched);
    const next = segments.slice(i + 1).find((s) => s.matched);
    // Only fill gaps bounded on BOTH sides: that is the page-boundary case.
    // An unmatched head or tail (LLM paraphrase) is left alone on purpose.
    if (!prev || !next) continue;
    const filled = await matchGapInZone(segments[i].fragment, prev, next, state);
    if (filled.length > 0) {
      state.gapsFilled += 1;
      segments.splice(i, 1, ...filled);
      i += filled.length - 1;
    }
  }
}

async function resolveEvent(event, pageCount) {
  const state = { pageCount, ambiguous: false, split: false, unmatchedFragments: 0, gapsFilled: 0, disambiguator: null, notes: [] };
  if (!event.text) {
    return { method: "unresolved", notes: ["event has no text to search for"], parts: [] };
  }
  // Without an explicit occurrence number, derive one from the character
  // offset if the payload carries it (the pipeline's wire format does).
  if (event.occurrence == null && event.startIndex != null && event.page != null) {
    event.occurrence = await deriveOccurrenceFromOffset(event, state);
  }
  // A context anchor (surrounding text) is resolved to a zone up front, and
  // used later to pick between multiple occurrences. An explicit occurrence
  // number takes precedence, so the zone is only computed when needed.
  if (event.context && event.occurrence == null) {
    event._zone = await locateContextZone(event, state);
  }
  const segments = await resolveFragment(event.text, event, state);
  await fillGapSegments(segments, state);
  state.unmatchedFragments = segments.filter((s) => !s.matched).length;
  let parts = segments.filter((s) => s.matched);

  // The search API missed at least part of the trigger: before settling for
  // a partial highlight or giving up, try the whitespace-tolerant matcher
  // against the page text (covers text-layer defects like missing spaces).
  if (state.unmatchedFragments > 0 && event.page != null) {
    const tolerant = await tolerantLocate(event, state);
    if (tolerant) {
      return {
        method: "tolerant-match",
        notes: state.notes,
        parts: [{ ...tolerant, boundingBox: rectsUnion(tolerant.rects) }],
      };
    }
  }

  if (parts.length === 0) {
    if (event.coordinates) {
      state.notes.push("text not found anywhere in the document; falling back to the LLM coordinates");
      return {
        method: "coordinates-fallback",
        notes: state.notes,
        parts: [
          {
            pageIndex: (event.page ?? 1) - 1,
            rects: null,
            boundingBox: [
              event.coordinates.left,
              event.coordinates.top,
              event.coordinates.width,
              event.coordinates.height,
            ],
          },
        ],
      };
    }
    return {
      method: "unresolved",
      notes: [
        ...state.notes,
        "text not found anywhere in the document and no coordinates supplied; flagged instead of guessing a highlight",
      ],
      parts: [],
    };
  }

  // Merge fragments that landed on the same page into one annotation.
  const byPage = new Map();
  for (const part of parts) {
    if (!byPage.has(part.pageIndex)) byPage.set(part.pageIndex, []);
    byPage.get(part.pageIndex).push(...part.rects);
  }
  const merged = [...byPage.entries()]
    .sort((a, b) => a[0] - b[0])
    .map(([pageIndex, rects]) => {
      const lineRects = mergeLineRects(rects);
      return { pageIndex, rects: lineRects, boundingBox: rectsUnion(lineRects) };
    });

  let method;
  if (!state.split && !state.ambiguous) method = "unique-text";
  else if (!state.split && state.ambiguous) method = `${state.disambiguator ?? "page"}-disambiguated`;
  else if (merged.length > 1) method = "split-across-pages";
  else method = "fuzzy-partial";
  if (state.gapsFilled > 0) {
    state.notes.push("gap at the page boundary filled by anchored sub-fragment search");
  }
  if (state.split && state.unmatchedFragments > 0 && method !== "fuzzy-partial") {
    state.notes.push(`${state.unmatchedFragments} fragment(s) of the LLM text could not be matched`);
  }
  if (method === "fuzzy-partial") {
    state.notes.push("exact text not found; highlighted the longest matching fragment(s)");
  }
  if (method === "split-across-pages") {
    state.notes.push(`sentence crosses a page boundary; highlighted on pages ${merged.map((m) => m.pageIndex + 1).join(" and ")}`);
  }
  return { method, notes: state.notes, parts: merged };
}


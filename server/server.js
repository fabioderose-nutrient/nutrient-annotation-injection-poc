// Server-side word search. Returns [{ pageIndex, rects: [[l,t,w,h],...] }].
// Queries are whitespace-normalized (Document Engine's search does not fold
// runs of spaces, while it does fold curly/straight quotes). Results are
// cached per processing run: real payloads repeat the same trigger string
// many times (e.g. one defined term emitting a dozen events).
let searchCache = new Map();

async function searchDocument(query, pageCount) {
  const q = String(query ?? "").replace(/\s+/g, " ").trim();
  if (q.length < 3) return [];
  if (searchCache.has(q)) return searchCache.get(q);
  const promise = (async () => {
    const params = new URLSearchParams({
      q,
      type: "text",
      start: "0",
      limit: String(Math.min(pageCount, 500)),
    });
    const res = await de(`/api/documents/${DOCUMENT_ID}/search?${params}`);
    if (!res.ok) return [];
    const body = await res.json();
    const hits = body?.data ?? [];
    return hits
      .filter((h) => !h.isAnnotation)
      .map((h) => ({
        pageIndex: h.pageIndex,
        rects: (h.rectsOnPage ?? []).filter((r) => r[2] >= 1 && r[3] >= 1),
      }))
      .filter((h) => h.rects.length > 0);
  })();
  searchCache.set(q, promise);
  return promise;
}

// Page text in reading order, used to derive occurrence numbers from the
// character offsets (startIndex) the extraction pipeline emits. Cached per run.
let pageTextCache = new Map();

async function getPageLines(pageIndex) {
  if (pageTextCache.has(pageIndex)) return pageTextCache.get(pageIndex);
  const promise = (async () => {
    const res = await de(`/api/documents/${DOCUMENT_ID}/pages/${pageIndex}/text`, {
      headers: { Accept: "application/json" },
    });
    if (!res.ok) return { text: "", lines: [], lineStarts: [] };
    const body = await res.json();
    const lines = body?.textLines ?? [];
    const lineStarts = [];
    let offset = 0;
    for (const line of lines) {
      lineStarts.push(offset);
      offset += line.contents.length + 1; // +1 for the joining newline
    }
    return { text: lines.map((l) => l.contents).join("\n"), lines, lineStarts };
  })();
  pageTextCache.set(pageIndex, promise);
  return promise;
}

// Tolerant matcher for a trigger: whitespace runs match any whitespace and
// curly/straight quotes are interchangeable (the two divergences observed
// between the pipeline's extracted text and the PDF text layer).
function triggerRegex(text, { looseSpaces = false } = {}) {
  const pattern = text
    .replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
    .replace(/['‘’]/g, "['‘’]")
    .replace(/["“”]/g, "[\"“”]")
    .replace(/\s+/g, looseSpaces ? "\\s*" : "\\s+");
  return new RegExp(pattern, "gi");
}

// Last-resort matcher for text-layer defects the search API cannot fold
// (e.g. a missing space in the PDF's text layer: "the period of12 weeks").
// The trigger is matched against the page text with whitespace optional,
// and the rects are estimated proportionally from the matched text lines.
async function tolerantLocate(event, state) {
  const { text, lines, lineStarts } = await getPageLines(event.page - 1);
  if (!text) return null;
  const matches = [...text.matchAll(triggerRegex(event.text, { looseSpaces: true }))];
  if (matches.length === 0) return null;
  let match = matches[0];
  if (matches.length > 1 && event.startIndex != null) {
    match = matches.reduce((a, b) =>
      Math.abs(b.index - event.startIndex) < Math.abs(a.index - event.startIndex) ? b : a
    );
    state.notes.push(`${matches.length} tolerant matches on page ${event.page}; picked the one nearest the character offset`);
  }
  const start = match.index;
  const end = start + match[0].length;
  const rects = [];
  for (let i = 0; i < lines.length; i++) {
    const lineStart = lineStarts[i];
    const lineLen = lines[i].contents.length;
    if (lineStart + lineLen <= start || lineStart >= end) continue;
    const from = Math.max(0, start - lineStart) / Math.max(1, lineLen);
    const to = Math.min(lineLen, end - lineStart) / Math.max(1, lineLen);
    rects.push([
      lines[i].left + lines[i].width * from,
      lines[i].top,
      lines[i].width * (to - from),
      lines[i].height,
    ]);
  }
  if (rects.length === 0) return null;
  state.notes.push(
    "trigger matched despite a text-layer defect (whitespace divergence); highlight zone estimated from the text lines"
  );
  return { pageIndex: event.page - 1, rects };
}

// The pipeline holds the character offset of each trigger within the page text
// (startIndex). Its text layer and Document Engine's disagree only by a few
// characters (quotes, spacing), so mapping the offset to the nearest
// occurrence position in Document Engine's page text gives a reliable
// per-page occurrence number without any change to the pipeline.
async function deriveOccurrenceFromOffset(event, state) {
  const { text } = await getPageLines(event.page - 1);
  if (!text) return null;
  const positions = [...text.matchAll(triggerRegex(event.text))].map((m) => m.index);
  if (positions.length === 0) return null;
  if (positions.length === 1) return 1;
  let best = 0;
  for (let i = 1; i < positions.length; i++) {
    if (Math.abs(positions[i] - event.startIndex) < Math.abs(positions[best] - event.startIndex)) best = i;
  }
  state.notes.push(
    `occurrence #${best + 1} of ${positions.length} on page ${event.page} derived from the character offset`
  );
  return best + 1;
}

// Small concurrency pool: resolves items in parallel while keeping results
// in input order.
async function mapPool(items, worker, size = 6) {
  const results = new Array(items.length);
  let next = 0;
  await Promise.all(
    Array.from({ length: Math.min(size, items.length) }, async () => {
      while (next < items.length) {
        const i = next++;
        results[i] = await worker(items[i], i);
      }
    })
  );
  return results;
}

